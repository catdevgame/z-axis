#!/usr/bin/env python3
"""Rebuild the retail-format SLUS_203.27 ELF from our linked ELF.

usage: elf_pack.py build/SLUS_203.27.elf build/SLUS_203.27

The retail file was produced by Sony's dvp-aware GNU ld (ee-ld), which writes a
layout modern ld does not: one PT_LOAD at file offset 0x1000, a .reginfo that is
not loaded, empty .vudata/.vubss markers, and eight zero-filled .DVP.overlay
placeholders plus .DVP.ovlytab/.DVP.ovlystrtab describing the VU1 overlays in
.vutext. Everything that carries game bytes (all loadable sections) is taken from
the linked ELF; the rest is regenerated from the constants below, which are
linker metadata only (no game data).
"""
import struct
import sys

from elftools.elf.elffile import ELFFile

E_FLAGS = 0x20924001          # EF_MIPS_ARCH_3 | E_MIPS_MACH_5900 | E_MIPS_ABI_EABI64 | EF_MIPS_NOREORDER
REGINFO_GPRMASK = 0xB00001FE  # union of input .reginfo masks as computed by ee-ld
REGINFO_ALIGN_QUIRK = 0x34    # ee-ld put .reginfo/.bss file offset 0x34 past .sbss's offset

# .DVP.overlay sections: (name, size, lma, vma). Names are generated by dvp-as.
OVERLAYS = [
    (".DVP.overlay..0x0.1425358099.24.0",     0x800, 0x22DB50, 0x0000),
    (".DVP.overlay..0x800.135334587.246.1",   0x800, 0x22E358, 0x0800),
    (".DVP.overlay..0x1000.135303355.38.2",   0x800, 0x22EB60, 0x1000),
    (".DVP.overlay..0x1800.135303355.349.3",  0x800, 0x22F368, 0x1800),
    (".DVP.overlay..0x2000.541320123.12.4",   0x800, 0x22FB70, 0x2000),
    (".DVP.overlay..0x2800.2181315547.423.5", 0x800, 0x230378, 0x2800),
    (".DVP.overlay..0x3000.1425358099.213.6", 0x800, 0x230B80, 0x3000),
    (".DVP.overlay..0x3800.568910523.1003.7", 0x510, 0x231388, 0x3800),
]

SHT_PROGBITS, SHT_STRTAB, SHT_NOBITS = 1, 3, 8
SHT_MIPS_REGINFO = 0x70000006
SHT_DVP_OVERLAY_TABLE, SHT_DVP_OVERLAY = 0x7FFFF420, 0x7FFFF421
A, W, X, GPREL = 0x2, 0x1, 0x4, 0x10000000

LOADABLE = [  # name, flags, align
    (".text", A | X, 0x40), (".vutext", A | X, 0x10), (".data", W | A, 0x40),
    (".rodata", A, 0x10), (".lit4", W | A | GPREL, 0x4), (".sdata", W | A | GPREL, 0x10),
    (".sbss", W | A | GPREL, 0x10), (".bss", W | A, 0x40),
]


def main(src, dst):
    elf = ELFFile(open(src, "rb"))
    secs = {s.name: s for s in elf.iter_sections()}
    symtab = elf.get_section_by_name(".symtab")
    entry = symtab.get_symbol_by_name("_start")[0]["st_value"]
    gp = symtab.get_symbol_by_name("_gp")[0]["st_value"]

    base = secs[".text"]["sh_addr"]
    seg_off = 0x1000
    out = bytearray(seg_off)
    shdrs = []  # (name, type, flags, addr, off, size, link, info, align, entsize)

    def put(off, data):
        if len(out) < off:
            out.extend(b"\0" * (off - len(out)))
        out[off:off + len(data)] = data

    filesz = 0
    for name, flags, align in LOADABLE:
        s = secs[name]
        addr, size = s["sh_addr"], s["sh_size"]
        off = seg_off + addr - base
        nobits = s["sh_type"] == "SHT_NOBITS"
        if not nobits:
            put(off, s.data())
            filesz = max(filesz, addr + size - base)
        shdrs.append([name, SHT_NOBITS if nobits else SHT_PROGBITS, flags, addr, off, size, 0, 0, align, 0])
    put(seg_off + filesz, b"")
    by = {h[0]: h for h in shdrs}
    memsz = by[".bss"][3] + by[".bss"][5] - base

    tail = by[".sbss"][4] + REGINFO_ALIGN_QUIRK
    by[".bss"][4] = tail
    vt = by[".vutext"]
    reginfo = [".reginfo", SHT_MIPS_REGINFO, 0, vt[3] + vt[5], tail, 0x18, 0, 0, 4, 1]
    d = by[".data"]
    vudata = [".vudata", SHT_PROGBITS, W | A, d[3] + d[5], d[4] + d[5], 0, 0, 0, 1, 0]
    b = by[".bss"]
    vubss = [".vubss", SHT_NOBITS, W | A, b[3] + b[5], tail, 0, 0, 0, 1, 0]
    put(tail, struct.pack("<6I", REGINFO_GPRMASK, 0, 0, 0, 0, gp))

    off = tail + 0x18
    ovl = []
    for name, size, lma, vma in OVERLAYS:
        ovl.append([name, SHT_DVP_OVERLAY, W | X, 0, off, size, 0, 0, 1, 0])
        put(off, b"\0" * size)
        off += size
    ostr = b"\0"
    tab = b""
    for name, size, lma, vma in OVERLAYS:
        tab += struct.pack("<3I", vubss[3] + len(ostr), lma, vma)
        ostr += name.encode() + b"\0"
    order = ([shdrs[0], shdrs[1], reginfo, shdrs[2], vudata] + shdrs[3:7] + [shdrs[7], vubss] + ovl)
    ovlytab_idx = len(order) + 1  # index (counting the null section) of .DVP.ovlystrtab
    order.append([".DVP.ovlytab", SHT_DVP_OVERLAY_TABLE, W, vubss[3], off, len(tab), ovlytab_idx + 1, 0, 4, 12])
    put(off, tab); off += len(tab)
    order.append([".DVP.ovlystrtab", SHT_STRTAB, W, vubss[3], off, len(ostr), 0, 0, 1, 0])
    put(off, ostr); off += len(ostr)

    # ee-ld kept the names of the stripped .symtab/.strtab at the front
    names = [".symtab", ".strtab", ".shstrtab"] + [h[0] for h in order]
    shstr = b"\0"
    name_off = {}
    for n in names:
        name_off[n] = len(shstr)
        shstr += n.encode() + b"\0"
    order.append([".shstrtab", SHT_STRTAB, 0, 0, off, len(shstr), 0, 0, 1, 0])
    put(off, shstr); off += len(shstr)
    shoff = (off + 3) & ~3
    put(shoff, b"")

    sh = struct.pack("<10I", *([0] * 10))
    for h in order:
        sh += struct.pack("<10I", name_off[h[0]], *h[1:])
    put(shoff, sh)

    ident = b"\x7fELF\x01\x01\x01" + b"\0" * 9
    ehdr = ident + struct.pack("<HHIIIIIHHHHHH", 2, 8, 1, entry, 0x34, shoff, E_FLAGS,
                               0x34, 0x20, 1, 0x28, len(order) + 1, len(order))
    phdr = struct.pack("<8I", 1, seg_off, base, base, filesz, memsz, 7, 0x1000)
    put(0, ehdr + phdr)
    open(dst, "wb").write(out)


if __name__ == "__main__":
    main(*sys.argv[1:3])
