#!/usr/bin/env python3
"""Generate build.ninja and the linker script for SLUS_203.27.

  .venv/bin/python configure.py            # re-run splat, then write build.ninja
  .venv/bin/python configure.py --no-split # only regenerate build.ninja / build/link.ld
  ninja                                    # build and verify (rom + ELF SHA1)

Layout notes
- splat writes SLUS_203.27.ld; we only use it for the per-section object order and
  write our own build/link.ld with the original output sections pinned to their
  original addresses (the original linker put each section on a 0x80 boundary and
  kept .vutext as its own section; splat's script would pack them at 0x10).
- C files are compiled with Sony's ee-gcc 2.9-ee-991111 (cc1 and its GNU as), the
  toolchain that reproduces the retail code; see tools/cc.sh and README.md.
"""
import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
YAML = "SLUS_203.27.yaml"
SPLAT_LD = "SLUS_203.27.ld"
BASENAME = "SLUS_203.27"

ROM_SHA1 = "f46a8b71b6a481428d34e6f4f64e3bb283ce336e"  # flat load image (vaddr 0x100000..0x279158)
ELF_SHA1 = "af35b83f0d773e613c91f21fa1e00a45efbbfec7"  # retail SLUS_203.27

# Output sections of the retail ELF: name -> (vaddr, nobits)
SECTIONS = [
    (".text",   0x00100000, False),
    (".vutext", 0x0022DB40, False),
    (".data",   0x00231900, False),
    (".rodata", 0x00261E80, False),
    (".lit4",   0x00272900, False),
    (".sdata",  0x00273280, False),
    (".sbss",   0x00279180, True),
    (".bss",    0x00279980, True),
]
GP = 0x0027A8F0

CFLAGS = os.environ.get("EE_CFLAGS", "-O2 -G16 -fno-strict-aliasing")

BINUTILS = "tools/binutils/mips-ps2-decompals-"
AS = BINUTILS + "as"
LD = BINUTILS + "ld"
OBJCOPY = BINUTILS + "objcopy"
ASFLAGS = "-EL -march=r5900 -mabi=eabi -G0 -no-pad-sections -Iinclude"


def run_splat():
    env = dict(os.environ)
    env["PATH"] = os.path.join(ROOT, "tools/binutils/shim") + os.pathsep + env["PATH"]
    with open(os.path.join(ROOT, "logs/split.log"), "w") as log:
        r = subprocess.run([sys.executable, "-m", "splat", "split", YAML],
                           cwd=ROOT, env=env, stdout=log, stderr=subprocess.STDOUT)
    if r.returncode:
        sys.exit("splat failed, see logs/split.log")


def parse_splat_ld():
    """Return {output_section: [object paths in order]} from splat's linker script."""
    pat = re.compile(r"^\s*(build/\S+?\.o)\((\.[A-Za-z0-9_]+)")
    order = {name: [] for name, _, _ in SECTIONS}
    for line in open(os.path.join(ROOT, SPLAT_LD)):
        m = pat.match(line)
        if not m:
            continue
        obj, sec = m.groups()
        if "/vutext" in obj:
            if sec == ".text":
                order[".vutext"].append(obj)
            continue
        if "/gap_" in obj:
            continue
        if sec in order and obj not in order[sec]:
            order[sec].append(obj)
    return order


def write_linker_script(order):
    out = ["/* generated by configure.py, do not edit */", "ENTRY(_start);",
           "SECTIONS", "{", f"    _gp = 0x{GP:08X};"]
    for name, vaddr, nobits in SECTIONS:
        sel = {".sbss": "(.sbss .scommon)", ".bss": "(.bss COMMON)"}.get(name, f"({name}*)")
        if name == ".vutext":
            sel = "(.text*)"
        out.append(f"    {name} 0x{vaddr:08X}{' (NOLOAD)' if nobits else ''} :")
        out.append("    {")
        for obj in order[name]:
            out.append(f"        {obj}{sel};")
        out.append("    }")
    out += ["    /DISCARD/ : { *(.reginfo) *(.MIPS.abiflags) *(.pdr) *(.comment) *(.mdebug*) *(.gnu.attributes) *(.note*) }",
            "}"]
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    with open(os.path.join(ROOT, "build/link.ld"), "w") as f:
        f.write("\n".join(out) + "\n")


def source_for(obj):
    """build/asm/cod/000000.o -> asm/cod/000000.s ; build/src/x.c.o -> src/x.c"""
    base = obj[len("build/"):-len(".o")]
    for cand in (base + ".s", base, base + ".c"):
        if os.path.exists(os.path.join(ROOT, cand)) and os.path.isfile(os.path.join(ROOT, cand)):
            return cand
    if base.endswith(".s") or base.endswith(".c"):
        return base
    return base + ".s"


def write_ninja(order):
    objs = []
    for name, _, _ in SECTIONS:
        for o in order[name]:
            if o not in objs:
                objs.append(o)
    n = []
    n.append("# generated by configure.py, do not edit")
    n.append(f"asflags = {ASFLAGS}")
    n.append(f"cflags = {CFLAGS}")
    n.append("rule as\n  command = %s $asflags $in -o $out\n  description = AS $in" % AS)
    # Sony ee-gcc 2.9-ee-991111 driver: cpp + cc1 + GNU as 2.9-ee-991111 (see tools/cc.sh)
    n.append("rule cc\n  command = tools/cc.sh \"$cflags\" $in $out\n  description = CC $in")
    n.append(("rule ld\n  command = %s -EL -nostdlib --no-check-sections -T build/link.ld "
              "-T undefined_syms_auto.txt -T undefined_funcs_auto.txt -Map build/%s.map -o $out $in\n"
              "  description = LD $out") % (LD, BASENAME))
    n.append("rule objcopy\n  command = %s -O binary $in $out\n  description = OBJCOPY $out" % OBJCOPY)
    n.append("rule elfpack\n  command = .venv/bin/python tools/elf_pack.py $in $out\n  description = ELFPACK $out")
    n.append("rule sha1\n  command = tools/check_sha1.sh $expected $in && touch $out\n  description = SHA1 $in")
    for o in objs:
        src = source_for(o)
        rule = "cc" if src.endswith(".c") else "as"
        n.append(f"build {o}: {rule} {src}")
    n.append(f"build build/{BASENAME}.elf: ld {' '.join(objs)} | build/link.ld")
    n.append(f"build build/{BASENAME}.rom: objcopy build/{BASENAME}.elf")
    n.append(f"build build/{BASENAME}: elfpack build/{BASENAME}.elf")
    n.append(f"build build/rom.ok: sha1 build/{BASENAME}.rom\n  expected = {ROM_SHA1}")
    n.append(f"build build/elf.ok: sha1 build/{BASENAME}\n  expected = {ELF_SHA1}")
    n.append("default build/rom.ok build/elf.ok")
    with open(os.path.join(ROOT, "build.ninja"), "w") as f:
        f.write("\n".join(n) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-split", action="store_true", help="skip running splat")
    args = ap.parse_args()
    os.chdir(ROOT)
    if not args.no_split:
        run_splat()
    order = parse_splat_ld()
    write_linker_script(order)
    write_ninja(order)
    print("wrote build.ninja and build/link.ld")


if __name__ == "__main__":
    main()
