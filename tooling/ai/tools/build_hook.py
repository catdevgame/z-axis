#!/usr/bin/env python3
"""Assemble pcsx2pad_hook.s and write the PCSX2 pnach that installs it.

Uses the decomp project's PS2 binutils (read-only):
  ../decomp/tools/binutils/mips-ps2-decompals-{as,ld,objcopy,objdump}

Output: pcsx2pad.pnach (committed) and, unless --no-install, a copy at
pcsx2-test-data/PCSX2/patches/SLUS-20327_67DB3ED8.pnach.

The built-in PCSX2 pnach for this game (patches.zip, a labelled
"[Widescreen 16:9]" group) is shadowed by any same-named file in the patches
folder, so it is copied into the output verbatim to keep the baseline
behaviour (it stays off unless widescreen patches are enabled).
"""

import argparse
import os
import struct
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
BINUTILS = os.path.join(HERE, "..", "decomp", "tools", "binutils", "mips-ps2-decompals-")
PATCHES_ZIP = "/Applications/PCSX2.app/Contents/Resources/patches.zip"
PNACH_NAME = "SLUS-20327_67DB3ED8.pnach"

CAVE = 0x000F8000          # code cave (unused EE RAM between EELOAD and the ELF)
CALL_SITE = 0x001188D0     # `jal scePadRead` in func_00118540
SCEPADREAD = 0x00211A30
ORIGINAL_CALL = 0x0C08468C  # jal 0x00211A30


def run(args):
    subprocess.run(args, check=True)


def build():
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "hook.o")
        elf = os.path.join(tmp, "hook.elf")
        binf = os.path.join(tmp, "hook.bin")
        run([BINUTILS + "as", "-EL", "-march=r5900", "-mabi=eabi", "-o", obj,
             os.path.join(HERE, "pcsx2pad_hook.s")])
        run([BINUTILS + "ld", "-EL", "-Ttext", "0x%08X" % CAVE, "-e", "pad_hook", "-o", elf, obj])
        run([BINUTILS + "objcopy", "-O", "binary", "-j", ".text", elf, binf])
        dis = subprocess.run([BINUTILS + "objdump", "-d", "-mmips:5900", elf],
                             check=True, capture_output=True, text=True).stdout
        code = open(binf, "rb").read()
    code += b"\0" * (-len(code) % 4)
    return code, dis


def builtin_pnach():
    try:
        with zipfile.ZipFile(PATCHES_ZIP) as z:
            return z.read(PNACH_NAME).decode("utf-8", "replace")
    except (OSError, KeyError):
        return None


def make_pnach(code):
    jal = 0x0C000000 | ((CAVE >> 2) & 0x03FFFFFF)
    lines = [
        "gametitle=Aggressive Inline (SLUS-20327)",
        "",
        "// pcsx2pad input-injection hook (generated by tools/build_hook.py from",
        "// tools/pcsx2pad_hook.s; see tools/PCSX2PAD.md). Unlabelled, so always on.",
        "// Redirect the game's only scePadRead call (0x%08X: jal 0x%08X, orig %08x)"
        % (CALL_SITE, SCEPADREAD, ORIGINAL_CALL),
        "patch=1,EE,%08X,word,%08X" % (CALL_SITE, jal),
        "// Hook body at 0x%08X (%d bytes)" % (CAVE, len(code)),
    ]
    for i in range(0, len(code), 4):
        w = struct.unpack_from("<I", code, i)[0]
        lines.append("patch=1,EE,%08X,word,%08X" % (CAVE + i, w))
    text = "\n".join(lines) + "\n"
    builtin = builtin_pnach()
    if builtin:
        body = "\n".join(l for l in builtin.splitlines() if not l.startswith("gametitle="))
        text += "\n// ---- PCSX2 built-in patches.zip/%s, copied verbatim ----\n" % PNACH_NAME
        text += body.strip("\n") + "\n"
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-install", action="store_true", help="only write tools/pcsx2pad.pnach")
    ap.add_argument("--disasm", action="store_true", help="print the hook disassembly")
    a = ap.parse_args()
    code, dis = build()
    if a.disasm:
        print(dis)
    text = make_pnach(code)
    out = os.path.join(HERE, "pcsx2pad.pnach")
    open(out, "w").write(text)
    print("wrote %s (%d hook bytes)" % (out, len(code)))
    if not a.no_install:
        dest_dir = os.path.join(HERE, "pcsx2-test-data", "PCSX2", "patches")
        if not os.path.isdir(dest_dir):
            sys.exit("missing %s (create the test data dir first)" % dest_dir)
        dest = os.path.join(dest_dir, PNACH_NAME)
        open(dest, "w").write(text)
        print("installed %s" % dest)


if __name__ == "__main__":
    main()
