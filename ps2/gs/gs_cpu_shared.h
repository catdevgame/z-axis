// Pixel pipeline helpers shared by the reference rasterizer
// (gs_cpu_backend.cpp) and the fast tiled rasterizer (gs_cpu_fast.cpp).
// Both must evaluate exactly the same expressions so that their output is
// bit identical (floating point contraction is decided per expression).

