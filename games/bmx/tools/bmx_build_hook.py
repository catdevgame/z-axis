#!/usr/bin/env python3
"""Assemble bmxpad_hook.s and write the PCSX2 pnach that installs it (BMX XXX, SLUS-20415, CRC 2999BCF9).

dm2_build_hook.py's method and binutils (the aggressive-inline decomp's PS2 binutils, read only). Output:
tools/bmxpad.pnach and, unless --no-install, a copy at $BMXPCSX2_DATA/PCSX2/patches/SLUS-20415_2999BCF9.pnach.
All lines are `patch=2` (at the ELF's start and every vsync), so the init call site 0x00100364 is
patched before the game reaches it. PCSX2's built-in pnach for the game (patches.zip) is shadowed by
a same-named file, so it is copied in verbatim.
"""

import argparse
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(1, os.path.join(HERE, '..', '..', 'dm2', 'tools'))   # (DM2's hook builder: games/dm2/tools)
import dm2_build_hook as base  # noqa: E402
sys.path.insert(0, os.path.join(HERE, '..', '..', '..', 'tools'))   # (tools/: zpaths.py)
import zpaths  # noqa: E402  (tools/paths.env: the data folder)

PNACH_NAME = "SLUS-20415_2999BCF9.pnach"
DATA_DIR = os.environ.get("BMXPCSX2_DATA", os.path.join(zpaths.ZAXIS_DATA, "bmx", "pcsx2-data-bmx"))

CAVE = 0x000F8000            # code cave (unused EE RAM below the ELF; checked zero in boot, menus and level)
PAD_CALL_SITE = 0x00117D60   # `jal scePadRead` in the pad function 0x001179D0
SCEPADREAD = 0x0022B280
PAD_ORIGINAL = 0x0C08ACA0    # jal 0x0022B280
INIT_CALL_SITE = 0x00100364  # `jal 0x00100300` (the VBlank callback setup)
INIT_ORIGINAL = 0x0C0400C0   # jal 0x00100300


def build():
    with tempfile.TemporaryDirectory() as tmp:
        obj, elf, binf = (os.path.join(tmp, n) for n in ("hook.o", "hook.elf", "hook.bin"))
        base.run([base.BINUTILS + "as", "-EL", "-march=r5900", "-mabi=eabi", "-o", obj, os.path.join(HERE, "bmxpad_hook.s")])
        base.run([base.BINUTILS + "ld", "-EL", "-Ttext", "0x%08X" % CAVE, "-e", "pad_hook", "-o", elf, obj])
        base.run([base.BINUTILS + "objcopy", "-O", "binary", "-j", ".text", elf, binf])
        dis = subprocess.run([base.BINUTILS + "objdump", "-d", "-mmips:5900", elf], check=True, capture_output=True, text=True).stdout
        nm = subprocess.run([base.BINUTILS + "nm", elf], check=True, capture_output=True, text=True).stdout
        code = open(binf, "rb").read()
    syms = {p[2]: int(p[0], 16) for p in (line.split() for line in nm.splitlines()) if len(p) == 3}
    code += b"\0" * (-len(code) % 4)
    return code, dis, syms


def make_pnach(code, syms):
    assert syms["pad_hook"] == CAVE, syms
    lines = [
        "gametitle=BMX XXX (SLUS-20415)",
        "",
        "// bmxpcsx2 input hook + VBlank counter + level-frame schedule (generated by",
        "// tools/bmx_build_hook.py from tools/bmxpad_hook.s). Unlabelled, so always on.",
        "// The game's only scePadRead call (0x%08X: jal 0x%08X, orig %08x) -> pad_hook" % (PAD_CALL_SITE, SCEPADREAD, PAD_ORIGINAL),
        "patch=2,EE,%08X,word,%08X" % (PAD_CALL_SITE, base.jal(syms["pad_hook"])),
        "// VBlank callback setup call (0x%08X, orig %08x) -> init_hook (installs the VBlank counter)" % (INIT_CALL_SITE, INIT_ORIGINAL),
        "patch=2,EE,%08X,word,%08X" % (INIT_CALL_SITE, base.jal(syms["init_hook"])),
        "// Hook body at 0x%08X (%d bytes)" % (CAVE, len(code)),
    ]
    for i in range(0, len(code), 4):
        lines.append("patch=2,EE,%08X,word,%08X" % (CAVE + i, struct.unpack_from("<I", code, i)[0]))
    text = "\n".join(lines) + "\n"
    base.PNACH_NAME = PNACH_NAME
    builtin = base.builtin_pnach()
    if builtin:
        body = "\n".join(l for l in builtin.splitlines() if not l.startswith("gametitle="))
        text += "\n// ---- PCSX2 built-in patches.zip/%s, copied verbatim ----\n" % PNACH_NAME + body.strip("\n") + "\n"
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-install", action="store_true", help="only write tools/bmxpad.pnach")
    ap.add_argument("--disasm", action="store_true", help="print the hook disassembly")
    a = ap.parse_args()
    code, dis, syms = build()
    if a.disasm:
        print(dis)
    print("symbols: " + ", ".join("%s=%08X" % (k, v) for k, v in sorted(syms.items(), key=lambda kv: kv[1])
                                  if not k.startswith(("_", "$"))))
    text = make_pnach(code, syms)
    out = os.path.join(HERE, "bmxpad.pnach")
    open(out, "w").write(text)
    print("wrote %s (%d hook bytes)" % (out, len(code)))
    if not a.no_install:
        dest_dir = os.path.join(DATA_DIR, "PCSX2", "patches")
        if not os.path.isdir(dest_dir):
            sys.exit("missing %s (bmxpcsx2.py setup makes the data dir)" % dest_dir)
        open(os.path.join(dest_dir, PNACH_NAME), "w").write(text)
        print("installed %s" % os.path.join(dest_dir, PNACH_NAME))


if __name__ == "__main__":
    main()
