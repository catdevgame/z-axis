#!/usr/bin/env python3
"""Assemble dm2pad_hook.s and write the PCSX2 pnach that installs it (DM2):
the mailbox, the VBlank counter and the level-frame input schedule.

Port of aggressive-inline/tools/build_hook.py. Uses the aggressive-inline
decomp project's PS2 binutils (read only):
  games/aggressive/workspace/decomp/tools/binutils/mips-ps2-decompals-*

Output: tools/dm2pad.pnach and, unless --no-install, a copy at
tools/pcsx2-data-dm2/PCSX2/patches/SLUS-20159_CEC42835.pnach.

All lines are `patch=2` (applied once when the ELF starts AND on every
vsync): the graphics-init call site 0x00100528 runs before the first vsync
after the ELF entry, so continuous-only (patch=1) lines would land too late
for it. The built-in PCSX2 pnach for this game (patches.zip: a labelled
"[Widescreen 16:9]" group, off unless widescreen patches are enabled) is
shadowed by any same-named file in the patches folder, so it is copied in
verbatim.
"""

import argparse
import os
import struct
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
BINUTILS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "aggressive", "workspace", "decomp", "tools", "binutils",
                        "mips-ps2-decompals-")
PATCHES_ZIP = "/Applications/PCSX2.app/Contents/Resources/patches.zip"
PNACH_NAME = "SLUS-20159_CEC42835.pnach"
DATA_DIR = os.environ.get("DM2PCSX2_DATA", os.path.join(HERE, "pcsx2-data-dm2"))

CAVE = 0x000F8000            # code cave (unused EE RAM between EELOAD and the ELF)
PAD_CALL_SITE = 0x00113108   # `jal scePadRead` in func_00112D98
SCEPADREAD = 0x001D9358
PAD_ORIGINAL = 0x0C0764D6    # jal 0x001D9358
INIT_CALL_SITE = 0x00100528  # `jal 0x00100388` (graphics init) in func_001004F8
INIT_ORIGINAL = 0x0C0400E2   # jal 0x00100388


def run(args):
    subprocess.run(args, check=True)


def build():
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "hook.o")
        elf = os.path.join(tmp, "hook.elf")
        binf = os.path.join(tmp, "hook.bin")
        run([BINUTILS + "as", "-EL", "-march=r5900", "-mabi=eabi", "-o", obj,
             os.path.join(HERE, "dm2pad_hook.s")])
        run([BINUTILS + "ld", "-EL", "-Ttext", "0x%08X" % CAVE, "-e", "pad_hook", "-o", elf, obj])
        run([BINUTILS + "objcopy", "-O", "binary", "-j", ".text", elf, binf])
        dis = subprocess.run([BINUTILS + "objdump", "-d", "-mmips:5900", elf],
                             check=True, capture_output=True, text=True).stdout
        nm = subprocess.run([BINUTILS + "nm", elf], check=True, capture_output=True, text=True).stdout
        code = open(binf, "rb").read()
    syms = {}
    for line in nm.splitlines():
        parts = line.split()
        if len(parts) == 3:
            syms[parts[2]] = int(parts[0], 16)
    code += b"\0" * (-len(code) % 4)
    return code, dis, syms


def builtin_pnach():
    try:
        with zipfile.ZipFile(PATCHES_ZIP) as z:
            return z.read(PNACH_NAME).decode("utf-8", "replace")
    except (OSError, KeyError):
        return None


def jal(addr):
    return 0x0C000000 | ((addr >> 2) & 0x03FFFFFF)


def make_pnach(code, syms):
    assert syms["pad_hook"] == CAVE, syms
    lines = [
        "gametitle=Dave Mirra Freestyle BMX 2 (SLUS-20159)",
        "",
        "// dm2pcsx2 input-injection hook + VBlank counter + level-frame schedule (generated by",
        "// tools/dm2_build_hook.py from tools/dm2pad_hook.s). Unlabelled, so always on.",
        "// The game's only scePadRead call (0x%08X: jal 0x%08X, orig %08x) -> pad_hook"
        % (PAD_CALL_SITE, SCEPADREAD, PAD_ORIGINAL),
        "patch=2,EE,%08X,word,%08X" % (PAD_CALL_SITE, jal(syms["pad_hook"])),
        "// Graphics init call (0x%08X, orig %08x) -> init_hook (installs the VBlank counter)"
        % (INIT_CALL_SITE, INIT_ORIGINAL),
        "patch=2,EE,%08X,word,%08X" % (INIT_CALL_SITE, jal(syms["init_hook"])),
        "// Hook body at 0x%08X (%d bytes)" % (CAVE, len(code)),
    ]
    for i in range(0, len(code), 4):
        w = struct.unpack_from("<I", code, i)[0]
        lines.append("patch=2,EE,%08X,word,%08X" % (CAVE + i, w))
    text = "\n".join(lines) + "\n"
    builtin = builtin_pnach()
    if builtin:
        body = "\n".join(l for l in builtin.splitlines() if not l.startswith("gametitle="))
        text += "\n// ---- PCSX2 built-in patches.zip/%s, copied verbatim ----\n" % PNACH_NAME
        text += body.strip("\n") + "\n"
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-install", action="store_true", help="only write tools/dm2pad.pnach")
    ap.add_argument("--disasm", action="store_true", help="print the hook disassembly")
    a = ap.parse_args()
    code, dis, syms = build()
    if a.disasm:
        print(dis)
    print("symbols: " + ", ".join("%s=%08X" % (k, v) for k, v in sorted(syms.items(), key=lambda kv: kv[1])
                                  if not k.startswith(("_", "$"))))
    text = make_pnach(code, syms)
    out = os.path.join(HERE, "dm2pad.pnach")
    open(out, "w").write(text)
    print("wrote %s (%d hook bytes)" % (out, len(code)))
    if not a.no_install:
        dest_dir = os.path.join(DATA_DIR, "PCSX2", "patches")
        if not os.path.isdir(dest_dir):
            sys.exit("missing %s (create the data dir first)" % dest_dir)
        dest = os.path.join(dest_dir, PNACH_NAME)
        open(dest, "w").write(text)
        print("installed %s" % dest)


if __name__ == "__main__":
    main()
