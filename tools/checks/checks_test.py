class FrameTableKeys(unittest.TestCase):
    """fncheck_corpus.Tree's frame table: the locals' places in the keys of their functions, not in the base (tools12)."""

    TABLE = ('// Generated by tools/fncheck_traced_gen.py: (%d functions)\n#include "ee/abi.h"\n\nnamespace\n{\n'
             '    const ee::EntrySave kSaves[] = {\n    {16, 8, 0x0}, {31, 8, 0x10},\n    {0, 0, 0}};\n'
             '    const uint16_t kLocals[] = {%s0};\n'
             '    const ee::FrameRow kRows[] = {\n%s    {0u, 0u, 0u, 0u, 0u, 0u, 0u}};\n'
             '    const ee::FrameTableRegistration g_frames{kRows, 2u, kSaves, kLocals};\n'
             '    const ee::CallSite kCallSites[] = {\n    {1u, 0x00101000u, 0x00102000u, 0x00101010u},\n    {0u, 0u, 0u, 0u}};\n'
             '    const ee::CallSiteRegistration g_callSites{kCallSites, 1u};\n}\n')

    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix='readable_tools_test')
        self.tree = fncheck_corpus.Tree.__new__(fncheck_corpus.Tree)
        self.tree.fcache, self.tree.build, self.tree.home = {}, self.dir, '/nowhere'
        self.tree.generated, self.tree.links, self.tree._unpath_re = [], [], None
        self.tree.rd = readable_digest

    def tearDown(self):
        shutil.rmtree(self.dir)

    def digest(self, places, size=0x30):
        rows = ('    {1u, 0x00101000u, 0x%xu, 0u, 2u, 0u, %du},\n' % (size, len(places)) +
                '    {1u, 0x00102000u, 0x20u, 2u, 0u, %du, 0u},\n' % len(places))
        path = os.path.join(self.dir, 'readable_frames.cpp')
        with open(path, 'w') as f:
            f.write(self.TABLE % (2, ''.join('0x%x, ' % p for p in places), rows))
        return self.tree.frames_digest(path)

    def test_a_locals_row_is_its_functions_not_the_bases(self):
        base = self.digest([])
        self.assertEqual(self.tree.frame_locals, {})
        self.assertEqual(self.digest([0x0, 0x10]), base)
        self.assertEqual(self.tree.frame_locals, {('dm2', 0x101000): (0x0, 0x10)})
        self.assertNotEqual(self.digest([], size=0x40), base)    # (a frame's size is every replay's)

    def test_the_locals_part_names_the_closures_bodies(self):
        self.digest([0x0, 0x10])
        self.tree.regs = {('dm2', 0x101000): [('a.cpp', 'drawThing', '')], ('dm2', 0x102000): [('b.cpp', 'caller', '')]}
        self.tree._reg_addrs = None
        self.assertEqual(self.tree.locals_part('dm2', 0x102000, {('b.cpp', 'caller')}), [])
        self.assertEqual(self.tree.locals_part('dm2', 0x102000, {('b.cpp', 'caller'), ('a.cpp', 'drawThing')}),
                         ['locals 101000=0,10'])
        self.assertEqual(self.tree.locals_part('dm2', 0x101000, set()), ['locals 101000=0,10'])
        self.assertEqual(self.tree.locals_part('ai', 0x101000, set()), [])

class BaseScriptCommands(unittest.TestCase):
    """fncheck_corpus.Tree.commands: a long command Ninja runs from a CMake-written script (Windows: `<output>.bat
    <digest of its text>`) is keyed by the script's text with the build's and tree's paths made alike, not by
    CMake's digest of it, which names the slot's own paths (tools41: slot4-bmx and slot5-bmx, one commit, two bases)."""

    def tree(self, top, slot, extra=''):
        b, h = os.path.join(top, 'out', slot + '-bmx'), os.path.join(top, 'wt', slot)
        os.makedirs(os.path.join(b, 'runtime', 'CMakeFiles'), exist_ok=True)
        with open(os.path.join(b, 'runtime', 'CMakeFiles', 'bmx.stamp-860dca4.bat'), 'w') as f:
            f.write('@echo off\ncd /D %s/runtime || (set FAIL_LINE=2& goto :ABORT)\n'
                    'python -B %s/tools/readable/readable_symbols.py headers --game bmx --out %s/runtime/symbols/bmx '
                    '--bind %s/tools/readable/bind/bmx.tsv%s --instance sce/libc.cpp sce/libm.cpp\n' % (b, h, b, h, extra))
        t = fncheck_corpus.Tree.__new__(fncheck_corpus.Tree)
        t.build, t.home, t.links = fncheck_corpus.norm_path(b), fncheck_corpus.norm_path(h), []
        digest = '91092afcaac59b56' if slot == 'slot4' else 'a0037c3d54a39381'
        t.ninja = lambda *args: 'runtime/CMakeFiles/bmx.stamp-860dca4.bat %s\nclang++ -c %s/runtime/src/a.cpp -o x.o\n' % (digest, h)
        return t

    def test_two_slots_alike(self):
        with tempfile.TemporaryDirectory() as top:
            a, b = self.tree(top, 'slot4').commands(), self.tree(top, 'slot5').commands()
            self.assertEqual(a, b)
            self.assertTrue(any('--bind $H/tools/readable/bind/bmx.tsv' in c for c in a), a)

    def test_the_script_text_counts(self):
        with tempfile.TemporaryDirectory() as top:
            self.assertNotEqual(self.tree(top, 'slot4').commands(), self.tree(top, 'slot5', ' --try-close').commands())


