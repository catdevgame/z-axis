class LocalScanGames(unittest.TestCase):
    """readable_localscan resolves a call to the functions its file's builds have (b7rider: DM2's rider's
    sphereQueryRaw call was judged against BMX XXX's sphereQueryRaw, which takes another word third)."""

    def scan(self, files):
        root = tempfile.mkdtemp()
        try:
            os.makedirs(os.path.join(root, 'tools'), exist_ok=True)
            os.makedirs(os.path.join(root, 'engine', 'zge'), exist_ok=True)
            os.symlink(ztree.TOOLS, os.path.join(root, 'tools', 'readable'))   # (the tree's readable_entries)
            files = dict(files)
            files.setdefault('plain_sources.txt', 'zge/math/\ndm2/\nbmx/\n')
            files.setdefault('dm2/instance_sources.txt', 'zge/math/shared.cpp\n')
            files.setdefault('bmx/instance_sources.txt', '')
            for rel, text in files.items():
                path = ztree.readable(root, rel)    # (by its key: engine/zge/..., games/dm2/...)
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, 'w').write(text)
            r = __import__('subprocess').run([sys.executable, '-B', os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                              'readable_localscan.py'), '--root', root, '--explained', os.devnull],
                                             capture_output=True, text=True)
            return r.returncode, r.stdout
        finally:
            shutil.rmtree(root)

    DM2_QUERY = ('namespace game::dm2::rider::collision {\n'
                 'int32_t sphereQueryRaw(Query *query, const ee::Float *centre, uint32_t filter, ee::Address filterArg)\n'
                 '{ return 0; }\nREADABLE_FUNCTION(sphereQueryRaw, Verified);\n}\n')
    BMX_QUERY = ('namespace game::bmx::rider::collision {\n'
                 'int32_t sphereQueryRaw(Query *query, const ee::Float *centre, uint32_t allFaces, uint32_t filter)\n'
                 '{ return 0; }\nREADABLE_FUNCTION(sphereQueryRaw, Draft);\n}\n')
    DM2_CALLER = ('namespace game::dm2::rider::collision {\n'
                  'void walkEdges(const ee::Float *centre, Query *query)\n{\n    ee::Local<Walk> walk;\n'
                  '    sphereQueryRaw(query, centre, kFilter, walk);\n}\n}\n')

    def test_a_game_folder_call_is_its_own_games(self):
        rc, out = self.scan({'dm2/rider/queries.cpp': self.DM2_QUERY + self.DM2_CALLER,
                             'bmx/rider/queries.cpp': self.BMX_QUERY})
        self.assertEqual((rc, out), (0, ''))

    def test_a_mismatch_in_the_callers_game_is_still_found(self):
        # (BMX XXX's own caller handing a Local to its own uint32_t parameter)
        caller = self.DM2_CALLER.replace('dm2', 'bmx')
        rc, out = self.scan({'dm2/rider/queries.cpp': self.DM2_QUERY,
                             'bmx/rider/queries.cpp': self.BMX_QUERY + caller})
        self.assertEqual(rc, 1)
        self.assertIn('bmx/rider/queries.cpp', out)
        self.assertIn('[value]', out)

    def test_a_shared_source_is_seen_by_the_instances_that_compile_it(self):
        shared = ('namespace zge {\nuint32_t sharedCount(uint32_t value)\n{ return value; }\n'
                  'READABLE_FUNCTION(sharedCount, Verified);\n}\n')
        caller = ('namespace game::dm2::rider {\nvoid user()\n{\n    ee::Local<uint32_t> n;\n'
                  '    zge::sharedCount(n);\n}\n}\n')
        rc, out = self.scan({'zge/math/shared.cpp': shared, 'dm2/rider/user.cpp': caller})
        self.assertEqual(rc, 1)
        self.assertIn('dm2/rider/user.cpp', out)
        # (an instance that does not compile the source has no such function)
        rc, out = self.scan({'zge/math/shared.cpp': shared, 'bmx/rider/user.cpp': caller.replace('dm2', 'bmx')})
        self.assertEqual((rc, out), (0, ''))


