class LayeringUpRef(unittest.TestCase):
    """readable_layering's up_ref names a function by C++'s lookup (tools37): zge/host's movies::playAgain() is
    host/movies.h's, not aggressive::playAgain; the engine naming one of AI's own functions is still found."""

    GAME = ('#include "host/movies.h"\nnamespace aggressive\n{\n    namespace\n    {\n        int32_t restart() { return 0; }\n'
            '    }\n    int32_t playAgain() { return restart(); }\n    READABLE_FUNCTION_WAITS(playAgain, Verified);\n}\n'
            'namespace zge\n{\n    void legalScreen() {}\n    READABLE_FUNCTION(legalScreen, Verified);\n'
            '    void aiOnlyHelper() {}\n    READABLE_FUNCTION(aiOnlyHelper, Verified);\n}\n')
    MOVIES = 'namespace game::host::movies\n{\n    void playAgain();\n}\n'
    STREAM = ('#include "host/movies.h"\nnamespace zge::host\n{\n    namespace\n    {\n'
              '        namespace movies = ::game::host::movies;\n    }\n    void streamEnd() { movies::playAgain(); }\n}\n')

    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix='layering_test')
        self.root = self.dir     # (a tree: the files below go to their folders by their keys)
        os.makedirs(os.path.join(self.root, 'engine', 'zge'))

    def tearDown(self):
        shutil.rmtree(self.dir)

    def up_refs(self, files):
        import readable_layering
        files = dict(files, **{'ee/game_id.h': 'enum class Game : uint8_t { Ai = 0, Dm2 = 1, Bmx = 2 };\n',
                               'aggressive/play_modes.cpp': self.GAME, 'host/movies.h': self.MOVIES,
                               'zge/game.h': 'namespace zge\n{\n    void legalScreen();\n}\n'})
        for rel, text in files.items():
            os.makedirs(os.path.dirname(ztree.readable(self.root, rel)), exist_ok=True)
            with open(ztree.readable(self.root, rel), 'w') as f:
                f.write(text)
        places = {}
        nowhere = os.path.join(self.dir, 'none')
        readable_layering.count(self.root, nowhere, nowhere, places)
        return sorted(p.split(': ', 1)[1] for p in places.get('up_ref', []))

    def test_an_alias_s_function_of_the_same_name_is_not_the_game_s(self):
        self.assertEqual(self.up_refs({'zge/host/movie_stream.cpp': self.STREAM}), [])

    def test_the_engine_naming_ai_s_function_is_found(self):
        call = 'namespace aggressive\n{\n    int32_t playAgain();\n}\nnamespace zge\n{\n    void f() { aggressive::playAgain(); }\n}\n'
        self.assertEqual(self.up_refs({'zge/host/movie_stream.cpp': self.STREAM, 'zge/menu.cpp': call}),
                         ['aggressive::playAgain'])

    def test_a_using_declaration_a_directive_and_a_symbol(self):
        using = 'namespace zge\n{\n    using aggressive::playAgain;\n    void f() { playAgain(); }\n}\n'
        directive = 'namespace zge\n{\n    void f()\n    {\n        using namespace ::aggressive;\n        playAgain();\n    }\n}\n'
        symbol = 'namespace zge\n{\n    const uint32_t kAgain = sym::playAgain;\n}\n'
        for code in (using, directive, symbol):
            self.assertEqual(self.up_refs({'zge/menu.cpp': code}), ['aggressive::playAgain'], code)
        # (a directive's scope ends with its block: a later playAgain() in zge is no name of AI's)
        ended = 'namespace zge\n{\n    void f()\n    {\n        using namespace ::aggressive;\n    }\n    void g() { playAgain(); }\n}\n'
        self.assertEqual(self.up_refs({'zge/menu.cpp': ended}), [])

    def test_the_engine_s_own_namespace_and_its_entries(self):
        # (AI's function defined in zge's namespace: named unqualified there it is AI's; an entry of zge/game.h is not)
        code = 'namespace zge\n{\n    void f() { aiOnlyHelper(); legalScreen(); }\n}\n'
        self.assertEqual(self.up_refs({'zge/menu.cpp': code}), ['zge::aiOnlyHelper'])
        # (the same name in another namespace, or a member, is not it)
        other = ('namespace zge::render\n{\n    struct Pass { void aiOnlyHelper(); };\n    void aiOnlyHelper();\n'
                 '    void f(Pass *p) { p->aiOnlyHelper(); aiOnlyHelper(); }\n}\n')
        self.assertEqual(self.up_refs({'zge/menu.cpp': other}), [])


class CompressedRecordings(unittest.TestCase):
    """fnrec_io and fnrec_pack (rzstd1): a recording compressed in place reads as its plain bytes, keeps its verdict
    cache key (fncheck_corpus.file_id: the plain size and the mtime) and its index, and a cut one fails clearly."""

    CTX = 32   # (a small context: the Python readers take the header's size)

    def plain(self, path, records=30, tail=b''):
        import struct
        out = [fnrec_io.HEADER.pack(b'FNREC1\0\0', 7, 0x00148408, self.CTX, 0)]
        for i in range(records):
            lines = (i * 37) % 900
            body = struct.pack('<IIQQIQ', fnrec_io.RECORD_MAGIC, 0, 100 + i, 10 * i, 0, 7) + bytes(2 * self.CTX)
            body += struct.pack('<I', lines) + bytes((i + j) & 0xFF for j in range(lines * fnrec_io.LINE))
            body += struct.pack('<II', 0, 0)   # (no outputs, no calls)
            out.append(body)
        with open(path, 'wb') as f:
            f.write(b''.join(out) + tail)
        os.utime(path, ns=(1_700_000_000_123_456_700, 1_700_000_000_123_456_700))

    @unittest.skipIf(fnrec_io.library() is None, 'no zstd library')
    def test_pack_in_place(self):
        import fnrec_index
        import fnrec_pack
        d = tempfile.mkdtemp()
        try:
            route = os.path.join(d, 'route')
            os.makedirs(route)
            a, b = os.path.join(route, '00148408.fnrec'), os.path.join(route, 'dm2-00100000.fnrec')
            self.plain(a)
            self.plain(b, tail=b'CALL' + bytes(60))   # (a record cut short by a kill: kept as it is)
            def data(p):
                with open(p, 'rb') as f:
                    return f.read()
            before = {p: (data(p), fncheck_corpus.file_id(p), fnrec_index.read_file(p)) for p in (a, b)}
            self.assertEqual(fnrec_pack.main([d, '--jobs', '2']), 0)
            for p, (data, fid, index) in before.items():
                self.assertTrue(fnrec_io.head(p)['packed'])
                self.assertLess(os.path.getsize(p), len(data))
                with fnrec_io.open_plain(p) as f:
                    self.assertEqual(f.read(), data)
                self.assertEqual(fncheck_corpus.file_id(p), fid)
                self.assertEqual(fnrec_index.read_file(p), index)
            self.assertEqual(before[b][2]['damaged'], True)
            self.assertEqual(sorted(os.listdir(route)), ['00148408.fnrec', 'dm2-00100000.fnrec'])
            self.assertEqual(fnrec_pack.main([d]), 0)   # (again: nothing to do, nothing changed)
            with fnrec_io.open_plain(a) as f:
                self.assertEqual(f.read(), before[a][0])
            # Cut short: the reader stops with an error, not with fewer bytes taken for the file.
            cut = os.path.join(d, 'cut.fnrec')
            with open(a, 'rb') as f, open(cut, 'wb') as g:
                g.write(f.read()[:-10])
            with self.assertRaises(Exception):
                with fnrec_io.open_plain(cut) as f:
                    f.read()
        finally:
            shutil.rmtree(d)

    def test_key_sizes_kept(self):
        import sqlite3
        d = tempfile.mkdtemp()
        try:
            p = os.path.join(d, '00148408.fnrec')
            self.plain(p, records=3)
            db = sqlite3.connect(os.path.join(d, 'v.sqlite'))
            sizes = fncheck_corpus.KeySizes(db)
            self.assertEqual(sizes.get(p, os.stat(p)), os.path.getsize(p))
            sizes.save()
            again = fncheck_corpus.KeySizes(db)
            self.assertIn(p, again.known)
            with open(p, 'ab') as f:
                f.write(b'x')
            self.assertEqual(again.get(p, os.stat(p)), os.path.getsize(p))   # (a changed file is read again)
            db.close()
        finally:
            shutil.rmtree(d)


